"""Printable evidence report for one incident (for 1930 / cybercrime.gov.in, or a bank's fraud team)."""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime
from html import escape

LEVEL = {"high": "HIGH RISK", "medium": "BE CAREFUL", "low": "NO WARNING SIGNS"}
FIELDS = ["id", "at", "kind", "display", "claimed", "identified_by", "level", "voice_verdict", "voice_score",
          "identity", "similarity", "script_score", "script_hits", "replay", "simulated", "operation_id", "reasons",
          "transcript", "bot_events"]


def _ts(t: int | None) -> str:
    return datetime.fromtimestamp(t).strftime("%d %b %Y, %H:%M:%S") if t else "—"


def to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(FIELDS)
    for r in rows:
        w.writerow([_ts(r["at"]) if f == "at" else r.get(f) for f in FIELDS])
    return buf.getvalue()


def html(r: dict, number_info: dict | None) -> str:
    hits = json.loads(r.get("script_hits") or "{}")
    reasons = json.loads(r.get("reasons") or "[]")
    rows = [
        ("Incident ID", f"KB-{r['id']:05d}"),
        ("Date and time", _ts(r["at"])),
        ("Type", "Live call" if r["kind"] == "live" else "Voice note / recording"),
        ("Caller number", r.get("display") or "Hidden / not given"),
        ("Number history", (f"{number_info.get('calls', 0)} calls, {number_info.get('alerts', 0)} earlier alerts, "
                            f"status: {number_info.get('status')}") if number_info else "—"),
        ("Claimed to be", r.get("claimed") or "Not stated"),
        ("How identity was found", r.get("identified_by") or "—"),
        ("Overall result", LEVEL.get(r.get("level"), r.get("level") or "—")),
        ("Voice (DetectifAI Aletheia)", f"{r.get('voice_verdict') or '—'}"
                                         + (f", AI-likelihood {r['voice_score']:.3f}" if r.get("voice_score") is not None else "")),
        ("Speaker match (DetectifAI Eidos)", f"{r.get('identity') or 'not checked'}"
                                              + (f", similarity {r['similarity']:.3f}" if r.get("similarity") is not None else "")),
        ("Scam-script score", f"{r.get('script_score') if r.get('script_score') is not None else '—'} / 100"),
        ("Scam phrases heard", "; ".join(f"{k}: {', '.join(v)}" for k, v in hits.items()) or "—"),
        ("Replay check", r.get("replay") or "not done"),
        ("Signals", ", ".join(reasons) or "—"),
        ("DetectifAI operation ID", r.get("operation_id") or "—"),
    ]
    bot_events = json.loads(r.get("bot_events") or "[]")
    if bot_events:
        rows.append(("Voice bot event history", "; ".join(
            f"{_ts(e['at'])} {e['state'].replace('_', ' ')} ({e['reason'].replace('_', ' ')})" for e in bot_events
        )))
    sim = ('<p class="sim">DEMO MODE: the voice results in this report were SIMULATED and are not evidence.</p>'
           if r.get("simulated") else "")
    body = "".join(f"<tr><th>{escape(k)}</th><td>{escape(str(v))}</td></tr>" for k, v in rows)
    return f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Incident KB-{r['id']:05d}</title>
<style>body{{font:15px/1.5 system-ui,'Nirmala UI',sans-serif;max-width:760px;margin:30px auto;padding:0 16px;color:#1d2a44}}
h1{{font-size:1.4rem;margin:0}}table{{border-collapse:collapse;width:100%;margin:16px 0}}th,td{{text-align:left;vertical-align:top;
padding:7px 9px;border-bottom:1px solid #e7dfd2}}th{{width:34%;color:#4a5672;font-weight:600}}td{{word-break:break-word}}.sim{{background:#fff3d6;padding:8px 12px;
border:1px dashed #c98a2b;border-radius:8px}}.note{{background:#f5f0e6;padding:10px 14px;border-radius:8px}}
pre{{white-space:pre-wrap;background:#f5f0e6;padding:10px;border-radius:8px}}button{{padding:8px 14px}}@media print{{button{{display:none}}}}</style>
</head><body>
<button onclick="print()">Print / save as PDF</button>
<h1>Suspicious call report: KB-{r['id']:05d}</h1>
<p>Generated by Kaun Bol Raha Hai?, built on DetectifAI Aletheia (deepfake detection) and Eidos (speaker verification).</p>
{sim}
<table>{body}</table>
<h3>What the caller said (transcript)</h3><pre>{escape(r.get('transcript') or '—')}</pre>
<div class="note"><b>Important:</b> these scores are evidence, not proof. Keep the original recording and call log.
<br><b>To report:</b> call <b>1930</b> (National Cyber Crime Helpline) or file at <b>cybercrime.gov.in</b>, and quote this incident ID.
If money was sent, also call your bank immediately and ask them to freeze the transaction.</div>
</body></html>"""
